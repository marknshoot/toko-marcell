#!/usr/bin/env python3
"""Write the copilot agent graph to ``docs/graph.mmd`` as a Mermaid diagram.

The diagram is generated from the real compiled graph, so it cannot drift from the code:
``api/tests/test_graph_diagram.py`` fails if the committed file is out of date.

The graph is built with the offline fake model and an in-memory checkpointer (the approval
pause only exists when there is somewhere to save the paused thread). No database, no network.

Usage::

    python scripts/dump_graph.py            # rewrite docs/graph.mmd
    python scripts/dump_graph.py --check    # exit 1 if docs/graph.mmd is out of date
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API_DIR = ROOT / "api"
OUTPUT = ROOT / "docs" / "graph.mmd"
FOOTER = "%% Generated by scripts/dump_graph.py from the compiled agent graph. Do not edit by hand.\n"


def render() -> str:
    """The Mermaid source of the compiled agent graph."""
    sys.path.insert(0, str(API_DIR))

    import copilot_agent
    from copilot_tools import ToolContext
    from langgraph.checkpoint.memory import InMemorySaver

    # Building the graph asks the database for category names on a cold cache; skip that here.
    copilot_agent._catalog_categories = lambda db_url: []  # noqa: SLF001

    saver = InMemorySaver()
    ctx = ToolContext(db_url="postgresql://unused@localhost:1/unused")
    turn = copilot_agent._Turn(  # noqa: SLF001
        started=time.perf_counter(),
        usage=copilot_agent.LLMCallCounter(),
        thread_id="graph",
        session_id=None,
        db_url=ctx.db_url,
        fake=True,
        checkpointer=saver,
    )
    agent = copilot_agent.build_agent(ctx, None, fake=True, checkpointer=saver, thread_id="graph", turn=turn)
    return agent.get_graph().draw_mermaid().rstrip("\n") + "\n\n" + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/graph.mmd is out of date")
    args = parser.parse_args()

    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run: python scripts/dump_graph.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({content.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
